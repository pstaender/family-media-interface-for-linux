// Extract the Tabler icons the admin panel uses (from Iconify's offline data,
// @iconify-json/tabler) into src/web/icons.ts. Run: bun run icons
import { icons } from "@iconify-json/tabler";
import { getIconData, iconToSVG } from "@iconify/utils";

const NAMES = [
  "device-tv", "shield-lock", "key", "logout", "home", "disc", "folder", "world",
  "lock", "lock-open", "clock", "hourglass", "calendar", "plus", "trash", "player-play",
  "alert-triangle", "circle-check", "chart-bar", "password", "menu-2",
];

let out = "// Generated by scripts/build-icons.ts from Tabler icons (via Iconify, MIT). Do not edit.\n";
out += "export const ICONS: Record<string, { viewBox: string; body: string }> = {\n";
for (const name of NAMES) {
  const data = getIconData(icons, name);
  if (!data) throw new Error(`unknown icon: ${name}`);
  const svg = iconToSVG(data);
  out += `  ${JSON.stringify(name)}: { viewBox: ${JSON.stringify(svg.attributes.viewBox)}, body: ${JSON.stringify(svg.body)} },\n`;
}
out += "};\n";
await Bun.write(new URL("../src/web/icons.ts", import.meta.url), out);
console.log(`wrote ${NAMES.length} icons`);
